"""Write reports/explainability.md (README Phase 7) from the Phase 7 outputs."""

from __future__ import annotations

import json
import math
from pathlib import Path

from bsp.explain.build import ExplainOutputs

LO, HI = 0.75, 0.85


def _pct(v: float) -> str:
    return "n/a" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v * 100:.1f}%"


def _table(header: list[str], rows: list[list[str]]) -> str:
    return "\n".join(["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |",
                      *["| " + " | ".join(r) + " |" for r in rows]])


def write_explainability_report(out: ExplainOutputs, path: Path) -> dict[str, bool]:
    detail = out.detail
    n = len(detail)
    three = detail["top_reasons"].map(lambda s: isinstance(s, str) and len(json.loads(s)) == 3).sum()
    has_interval = detail[["p10", "p90"]].notna().all(axis=1).sum()
    conformal_share = (detail["interval_method"] == "conformal_walk_forward").mean()
    overall = out.coverage_year[out.coverage_year["budget_id"] == "all test years"].set_index("model")
    by_year = out.coverage_year[out.coverage_year["budget_id"] != "all test years"]
    verdict = {"three_reasons": three == n, "interval": has_interval == n}
    lines = ["# Phase 7: explanations and calibrated intervals", "",
             "Generated by `make train` (`src/bsp/explain/`). Everything is out-of-sample (walk-forward folds); the FY2024-25 and "
             "FY2025-26 hold-out and the live year were not touched. Nothing here changes a forecast or rank. Nothing is investment advice.", "",
             "## Method", "",
             "- **SHAP / attributions** (`reports/shap_values_sector.csv`, `reports/shap_values_stock.csv`): one row per prediction and feature. "
             "LightGBM models use SHAP's TreeExplainer, for the expected-excess-return regressor (`target = expected_return`) and for the "
             "ranker's raw score (`target = rank_score`). The Bayesian model's posterior-mean predictor is exactly additive (sector intercept + "
             "surprise slope x surprise + controls), so its attributions are exact; the blend and stack apply their own weights to their "
             "components' attributions. Each row set satisfies baseline + sum of contributions = forecast (check below).",
             "- **Three reasons** (`bsp/explain/reasons.py`, wording in `config/feature_reasons.json`): the three features with the largest "
             "absolute contribution to the expected excess return, with the feature's value, the effect in percentage points and a source "
             "reference. The baseline is never a reason. The reasons explain the expected excess return that the interval wraps; the rank "
             "comes from the ranker, whose order usually but not always agrees.",
             "- **Intervals** (`bsp/explain/conformal.py`, MAPIE split conformal, 80%): for each test budget, the calibration errors are all "
             "earlier out-of-sample forecasts of the same model whose 12m label was known on its day 0. With fewer than 3 such budgets the "
             "interval is the model's own out-of-fold residual interval (`interval_method` in `reports/predictions_detail.csv`). Conformal "
             "guarantees assume exchangeable errors, which returns over time are not, so coverage is checked, not assumed.",
             "- **Table:** `data/csv/predictions.csv` (loaded into the `predictions` table by `make load`) has `model_version, entity, "
             "budget_id, expected_excess, p10, p90, p_beat, rank, top_reasons` (a JSON list of three strings). `rank` is 1 = best within the "
             "model and budget over all entities. `model_version` names the model, seed and a hash of the input CSVs.", "",
             "## Exit criteria", "",
             f"- **Every prediction has three reasons and an interval:** {three} of {n} predictions have exactly three reasons and "
             f"{has_interval} of {n} have p10 and p90 -> **{'PASS' if verdict['three_reasons'] and verdict['interval'] else 'FAIL'}**. "
             f"{_pct(conformal_share)} of the intervals are walk-forward conformal; the rest (the first test budgets, before three "
             "calibration budgets are resolved) use the out-of-fold residual interval.", ""]
    native = detail[~detail["is_control"]].dropna(subset=["actual", "lo", "hi"])
    native_cov = native.assign(c=(native["actual"] >= native["lo"]) & (native["actual"] <= native["hi"])).groupby("model")["c"].mean()
    rows = []
    for model, r in overall.iterrows():
        inside = bool(LO <= float(r["coverage"]) <= HI)
        verdict[f"coverage_{model}"] = inside
        rows.append([str(model), str(r["level"]), str(int(float(r["n"]))), _pct(float(r["coverage"])), "within" if inside else "OUTSIDE",
                     _pct(float(native_cov.get(model, float("nan")))), f"{float(r['mean_width']) * 100:.1f} pp"])
    lines += ["- **Walk-forward 80% coverage (target 75-85%)**, 14 budget-sensitive sectors / stocks outside the control sector, all test years:", "",
              _table(["Model", "Level", "Forecasts", "Coverage (reported interval)", "Target 75-85%", "Coverage of the model's own interval", "Mean width"], rows), ""]
    lines += ["## Coverage by test year (reported interval)", ""]
    pivot = by_year.pivot_table(index="budget_id", columns="model", values="coverage")
    lines += [_table(["Budget", *[str(c) for c in pivot.columns]], [[str(b), *[_pct(float(v)) for v in pivot.loc[b]]] for b in pivot.index]), "",
              "Each year has 14 sectors (a coverage step is 7.1 points) or about 100 stocks, so single years are noisy.", ""]
    lines += ["## Coverage by regime (reported interval)", ""]
    regime = out.coverage_regime
    rrows = [[str(r["model"]), str(r["regime"]), str(r["value"]), str(int(r["n"])), _pct(float(r["coverage"]))] for r in regime.to_dict("records")]
    lines += [_table(["Model", "Regime flag", "Value", "Forecasts", "Coverage"], rrows), "",
              "Regime flags come from the sector feature store: election year (`budget_events.csv`), Covid era (FY2021-22 and FY2022-23), "
              "high volatility (India VIX above 20 on budget day).", ""]
    add = out.additivity.groupby("model")["max_abs_gap"].max()
    lines += ["## Additivity check (baseline + contributions against the stored forecast)", "",
              _table(["Model", "Largest absolute gap (excess-return fraction)"], [[str(m), f"{float(g):.2e}"] for m, g in add.items()]), "",
              "The LightGBM-based gaps are floating-point noise. The Bayesian model's gap is Monte-Carlo noise: its stored forecast is the mean of "
              "posterior-predictive draws, its attribution is for the posterior-mean predictor; the blend and stack inherit that.", ""]
    latest = detail["budget_id"].max()
    lines += ["## Example reasons (latest test budget, highest-ranked entity per model)", ""]
    for model, g in detail[detail["budget_id"] == latest].groupby("model"):
        top = g.sort_values("rank").iloc[0]
        lines += [f"**{model}, {top['entity']}, {latest}** (expected {top['expected_excess'] * 100:+.1f}%, 80% interval "
                  f"{top['p10'] * 100:+.1f}% to {top['p90'] * 100:+.1f}%):", ""] + [f"- {b}" for b in json.loads(top["top_reasons"])] + [""]
    lines += ["## Limitations", "",
              "- The attributions describe the model, not the economy: a high contribution means the fitted model leaned on that feature, "
              "not that the feature caused the return. With 12 sector test years, the models themselves are weak (see `reports/models.md`).",
              "- Features the model could not see (missing values) are reported as not available; LightGBM still routes them down a default "
              "branch, so a missing value can carry a contribution.",
              "- Year-level features (fiscal deficit, subsidies, macro series) take the same value for all sectors in a budget, so a tree can use them "
              "as a stand-in for the year; their reasons say what the model used, not that the deficit moved a sector's return.",
              "- The FPI, speech and fundamentals families are mostly missing, so they rarely appear among the top three.",
              "- `credibility_pct` has extreme outliers in some early rows (up to 43,964%), which can dominate a reason; this is a data issue "
              "recorded here, not changed.", ""]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return verdict
